# ─────────────────────────────────────────────────────────────
# 문제 규칙
# ─────────────────────────────────────────────────────────────
#   두 정수 a, b가 주어질 때 a와 b 사이(양 끝 포함)의 모든 정수 합을 반환한다.
#   - a > b일 수도 있다(순서 보장 안 됨).
#   - 예) a=3, b=5 → 3+4+5 = 12,  a=3, b=3 → 3
#   제약: -10,000,000 ≤ a, b ≤ 10,000,000 → 범위가 최대 2천만 개

# ─────────────────────────────────────────────────────────────
# 풀이 1: 작은 값~큰 값 직접 루프 (처음 접근)
# ─────────────────────────────────────────────────────────────
# 핵심 아이디어:
#   a, b 중 작은 값을 start, 큰 값을 end로 정한 뒤 start..end를 더한다.
#   직관적이지만 범위 길이만큼 도는 O(n) — 2천만이면 2천만 번 반복.
def solution1(a, b):
    result = 0
    start = 0
    end = 0

    if a <= b:
        start = a
        end = b
    else:
        start = b
        end = a

    for i in range(start, end+1):
        result += i

    return result

# ─────────────────────────────────────────────────────────────
# 풀이 2: sum(range(...)) (파이썬다운, 여전히 O(n))
# ─────────────────────────────────────────────────────────────
# 핵심 아이디어:
#   min/max로 범위를 잡고 sum(range(...))로 누적 변수·루프를 한 줄로 압축.
#   가독성은 좋지만 내부적으로 모든 수를 더하므로 시간은 여전히 O(n).
def solution2(a, b):
    start = min(a,b)
    end = max(a,b)
    return sum(range(start,end+1))

# ─────────────────────────────────────────────────────────────
# 풀이 3: 등차수열 합 공식(가우스) — O(1), 추천
# ─────────────────────────────────────────────────────────────
# 핵심 아이디어 (가우스 공식의 원리):
#   연속된 정수 start..end를 양끝에서 짝지으면 합이 모두 같다.
#     start + end = (start+1) + (end-1) = ... = (start + end)
#   그런 짝이 '개수/2'개 있으므로  합 = (start + end) × 개수 ÷ 2.
#   여기서
#     - 첫값+끝값 = a + b      (순서와 무관하게 동일 → min/max 불필요)
#     - 개수      = |a - b| + 1 (양 끝 포함이라 +1)
#   따라서 합 = (a + b) × (|a-b| + 1) // 2  → 범위 크기와 무관하게 상수 시간.
#   (// 는 정수 나눗셈: 두 끝값의 합×개수는 항상 짝수라 나머지 없이 떨어진다.)
def solution3(a, b):
    return (a+b) * (abs(a-b)+1) // 2

# ─────────────────────────────────────────────────────────────
# 복잡도 분석
# ─────────────────────────────────────────────────────────────
# 범위 길이가 n(=|a-b|+1)일 때,
# 풀이 1·2: 시간 O(n) — 모든 수를 더함 (2천만 범위면 2천만 연산)
# 풀이 3   : 시간 O(1) — 공식 한 번. 범위가 아무리 커도 일정.
# 공간: 셋 다 O(1) (단, range는 지연 생성이라 리스트로 펼치지 않음)
# 결론: 연속 정수 합은 공식으로 O(1)이 가능 → 큰 범위에선 풀이 3이 명확히 우월.

# ─────────────────────────────────────────────────────────────
# 이 문제에서 배운 것 (Takeaways)
# ─────────────────────────────────────────────────────────────
#   1. 연속 정수의 합은 루프(O(n)) 대신 등차수열 합 공식으로 O(1)에 구한다.
#   2. (a+b)는 순서와 무관 → min/max 없이도 첫값+끝값이 그대로 a+b다.
#   3. 제약(범위 2천만)을 먼저 읽고 "루프면 느리다 → 공식으로" 판단하는 습관.
#   4. start/end를 if/else로 나누기보다 min(a,b)/max(a,b) 한 줄이 더 읽기 쉽다.

# ─────────────────────────────────────────────────────────────
# 테스트
# ─────────────────────────────────────────────────────────────
test_cases = [
    ((3, 5), 12),
    ((3, 3), 3),
    ((5, 3), 12),
]

run_tests([solution1, solution2, solution3], test_cases)