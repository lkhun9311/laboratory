# ─────────────────────────────────────────────────────────────
# 문제 규칙
# ─────────────────────────────────────────────────────────────
#   문자열 s가 "길이가 4 또는 6이면서 전부 숫자"이면 True, 아니면 False.
#   - 예) "a234" → False(문자 포함), "1234" → True
#   제약: 길이 1~8

# ─────────────────────────────────────────────────────────────
# 풀이 1: isdecimal() (권장)
# ─────────────────────────────────────────────────────────────
# 핵심 아이디어:
#   len(s) in (4,6)을 먼저 검사 → and 단락평가로 길이가 틀리면 뒤를 건너뛴다(O(1) 우선).
#   숫자 검사는 isdigit()이 아니라 isdecimal()을 쓴다:
#     - isdigit()은 위첨자 '²','³' 등도 True라 "²²²²"가 잘못 통과할 수 있다.
#     - isdecimal()은 십진 숫자 문자만 True → 이 문제 의도("0~9")에 더 정확.
def solution1(s):
    return len(s) in (4,6) and s.isdecimal()

# ─────────────────────────────────────────────────────────────
# 풀이 2: 0~9 직접 검사 (가장 명시적)
# ─────────────────────────────────────────────────────────────
# 핵심 아이디어:
#   모든 글자가 "0123456789"에 속하는지 all()로 확인 →
#   유니코드 함정 없이 'ASCII 0~9만'을 명확히 보장한다. 의도가 코드에 그대로 드러남.
def solution2(s):
    return len(s) in (4,6) and all(c in "0123456789" for c in s)

# ─────────────────────────────────────────────────────────────
# 복잡도 분석
# ─────────────────────────────────────────────────────────────
# 시간: O(n) — 길이 검사 O(1) 후, 숫자 검사가 전체 글자를 훑는 게 하한
# 공간: O(1) — 추가 자료구조 없음
# 결론: 두 풀이 모두 O(n)로 동일. 차이는 성능이 아니라 "엄밀성/표현"의 영역.

# ─────────────────────────────────────────────────────────────
# 이 문제에서 배운 것 (Takeaways)
# ─────────────────────────────────────────────────────────────
#   1. and 단락평가 — 싼 조건(길이)을 먼저 두면 비싼 조건(전체 스캔)을 아낀다.
#   2. 숫자 판별 3종 구분: isdigit()(위첨자 포함) ⊃ isdecimal()(십진) , isnumeric()(분수·로마숫자까지).
#      "0~9"를 원하면 isdigit()이 아니라 isdecimal()이 안전하다.
#   3. 가장 명시적으로 하려면 all(c in "0123456789" for c in s)로 직접 검사한다.

# ─────────────────────────────────────────────────────────────
# 테스트
# ─────────────────────────────────────────────────────────────
test_cases = [
    ("a234", False),
    ("1234", True),
    ("12345", False),   # 길이 5 → 4도 6도 아님
    ("²²²²", False),    # isdigit()이면 잘못 통과 — isdecimal()/직접검사는 정상 False
]

run_tests([solution1, solution2], test_cases)